-- RNF08 (Marco 2): segundo fator por biometria do celular (passkey / WebAuthn).
-- O servidor guarda só a chave pública; a digital ou o rosto nunca saem do aparelho.
CREATE TABLE credencial_biometrica (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario BIGINT NOT NULL,
  credential_id VARCHAR(512) NOT NULL UNIQUE,
  user_handle VARCHAR(128) NOT NULL,
  chave_publica_cose VARCHAR(2048) NOT NULL,
  contador_assinatura BIGINT NOT NULL DEFAULT 0,
  apelido VARCHAR(80) NOT NULL,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ultimo_uso_em TIMESTAMP,
  CONSTRAINT fk_credencial_biometrica_usuario FOREIGN KEY (id_usuario) REFERENCES usuario(id)
);

CREATE INDEX idx_credencial_biometrica_usuario ON credencial_biometrica (id_usuario);
CREATE INDEX idx_credencial_biometrica_handle ON credencial_biometrica (user_handle);

