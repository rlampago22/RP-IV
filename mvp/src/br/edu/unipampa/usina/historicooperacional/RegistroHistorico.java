package br.edu.unipampa.usina.historicooperacional;

import br.edu.unipampa.usina.persistencia.ConexaoBanco;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.time.Instant;
import java.time.LocalDate;
import java.time.ZoneId;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Persistência do histórico operacional (RF16/RF17), na tabela {@code nucleo.historico_operacional}
 * do banco do sistema (antes: arquivo {@code dados/historico-operacional.csv}) — mesma tabela que o
 * núcleo e o backend compartilham, mesmo padrão de {@code RegistroAuditoria}.
 *
 * <p>Sem cadeia de hash: detecção de adulteração é responsabilidade do {@code RegistroAuditoria}
 * (RNF05). Aqui o objetivo é dado operacional consultável, não trilha inviolável — por isso não há
 * trava de escrita entre processos: cada linha é um INSERT independente, sem sequência a disputar.
 */
public final class RegistroHistorico implements AutoCloseable {
    public static final int LIMITE_PADRAO = 500;
    public static final int LIMITE_MAXIMO = 5000;

    public static final String TABELA = "nucleo.historico_operacional";
    /** CSV usado até a migração para o banco; importado uma vez se a tabela estiver vazia. */
    public static final Path ARQUIVO_LEGADO = Path.of("dados", "historico-operacional.csv");

    private static final String COLUNAS =
        "reator_id, instante, temperatura, pressao, radiacao, fluxo_resfriamento, "
            + "sensores_em_alarme, sensores_reconhecidos, sensores_em_observacao, sensores_em_falha, "
            + "operador, papeis_operador, origem_operador";

    private final ConexaoBanco banco;
    private Connection conexao;

    public RegistroHistorico(ConexaoBanco banco) {
        this.banco = banco;
        garantirTabela();
    }

    /** Banco padrão do sistema, já trazendo o {@code dados/historico-operacional.csv} antigo se for a 1ª vez. */
    public static RegistroHistorico abrirPadrao() {
        RegistroHistorico registro = new RegistroHistorico(ConexaoBanco.padrao());
        int importadas = registro.importarCsvLegado(ARQUIVO_LEGADO);
        if (importadas > 0) {
            System.out.println("[HISTORICO] " + importadas + " linhas de " + ARQUIVO_LEGADO.toAbsolutePath()
                + " importadas para " + TABELA + ".");
        }
        return registro;
    }

    /**
     * Mesma estrutura da migração {@code backend/.../V7__criar_historico_operacional_nucleo.sql}.
     * Fica aqui também (idempotente) para o núcleo funcionar com um banco que o backend ainda não
     * migrou e com o H2 em memória dos testes.
     */
    private synchronized void garantirTabela() {
        try (Statement sql = conexao().createStatement()) {
            sql.execute("CREATE SCHEMA IF NOT EXISTS nucleo");
            sql.execute(
                "CREATE TABLE IF NOT EXISTS " + TABELA + " ("
                    + "sequencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "reator_id VARCHAR(10) NOT NULL, "
                    + "instante VARCHAR(40) NOT NULL, "
                    + "temperatura DOUBLE PRECISION NOT NULL, "
                    + "pressao DOUBLE PRECISION NOT NULL, "
                    + "radiacao DOUBLE PRECISION NOT NULL, "
                    + "fluxo_resfriamento DOUBLE PRECISION NOT NULL, "
                    + "sensores_em_alarme VARCHAR(200) NOT NULL DEFAULT '', "
                    + "sensores_reconhecidos VARCHAR(200) NOT NULL DEFAULT '', "
                    + "sensores_em_observacao VARCHAR(200) NOT NULL DEFAULT '', "
                    + "sensores_em_falha VARCHAR(200) NOT NULL DEFAULT '', "
                    + "operador VARCHAR(160) NOT NULL DEFAULT '', "
                    + "papeis_operador VARCHAR(200) NOT NULL DEFAULT '', "
                    + "origem_operador VARCHAR(30) NOT NULL)"
            );
        } catch (SQLException error) {
            descartarConexao();
            throw new IllegalStateException(
                "Não foi possível preparar a tabela de histórico em " + banco.descricao() + ": " + error.getMessage(),
                error
            );
        }
    }

    public synchronized void registrar(SnapshotOperacional snapshot) {
        try {
            Connection c = conexao();
            try (PreparedStatement insert = c.prepareStatement(
                "INSERT INTO " + TABELA + " (" + COLUNAS + ") VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)")) {
                preencher(insert, snapshot);
                insert.executeUpdate();
            }
        } catch (SQLException error) {
            descartarConexao();
            throw new IllegalStateException("Não foi possível gravar o histórico operacional: " + error.getMessage(), error);
        }
    }

    private static void preencher(PreparedStatement insert, SnapshotOperacional snapshot) throws SQLException {
        insert.setString(1, snapshot.reatorId());
        insert.setString(2, snapshot.instante().toString());
        insert.setDouble(3, snapshot.temperatura());
        insert.setDouble(4, snapshot.pressao());
        insert.setDouble(5, snapshot.radiacao());
        insert.setDouble(6, snapshot.fluxoResfriamento());
        insert.setString(7, juntar(snapshot.sensoresEmAlarme()));
        insert.setString(8, juntar(snapshot.sensoresReconhecidos()));
        insert.setString(9, juntar(snapshot.sensoresEmObservacao()));
        insert.setString(10, juntar(snapshot.sensoresEmFalha()));
        insert.setString(11, snapshot.operador());
        insert.setString(12, juntar(snapshot.papeisOperador()));
        insert.setString(13, snapshot.origemOperador().name());
    }

    private static String juntar(List<String> lista) {
        return String.join("|", lista);
    }

    /** Todas as linhas, em ordem de gravação, lidas do banco. */
    public synchronized List<SnapshotOperacional> consultar() {
        try (Statement sql = conexao().createStatement();
             ResultSet linhas = sql.executeQuery(
                 "SELECT " + COLUNAS + " FROM " + TABELA + " ORDER BY sequencia")) {
            List<SnapshotOperacional> snapshots = new ArrayList<>();
            while (linhas.next()) {
                snapshots.add(deLinha(linhas));
            }
            return List.copyOf(snapshots);
        } catch (SQLException error) {
            descartarConexao();
            throw new IllegalStateException("Não foi possível consultar o histórico: " + error.getMessage(), error);
        }
    }

    private static SnapshotOperacional deLinha(ResultSet linha) throws SQLException {
        return new SnapshotOperacional(
            linha.getString(1),
            Instant.parse(linha.getString(2)),
            linha.getDouble(3),
            linha.getDouble(4),
            linha.getDouble(5),
            linha.getDouble(6),
            separar(linha.getString(7)),
            separar(linha.getString(8)),
            separar(linha.getString(9)),
            separar(linha.getString(10)),
            linha.getString(11),
            separar(linha.getString(12)),
            OperadorDeServico.Origem.valueOf(linha.getString(13))
        );
    }

    private static List<String> separar(String campo) {
        String limpo = campo == null ? "" : campo.trim();
        return limpo.isEmpty() ? List.of() : List.of(limpo.split("\\|"));
    }

    /**
     * Consulta filtrada (RF16). O filtro roda em memória sobre o que já foi lido do banco —
     * adequado à ordem de grandeza do MVP; um volume muito maior pediria o filtro em SQL.
     */
    public synchronized ResultadoConsulta consultar(FiltroHistorico filtro, int limite) {
        int teto = Math.min(limite <= 0 ? LIMITE_PADRAO : limite, LIMITE_MAXIMO);
        List<SnapshotOperacional> casaram = consultar().stream()
            .filter(filtro::aceita)
            .toList();
        boolean truncado = casaram.size() > teto;
        return new ResultadoConsulta(
            truncado ? casaram.subList(0, teto) : casaram,
            casaram.size(),
            truncado
        );
    }

    public synchronized int tamanho() {
        return consultar().size();
    }

    /**
     * RF16 — agrupa o histórico em saídas de operação: um resumo por (dia local + operador).
     *
     * <p>O dia é calculado no fuso informado, não em UTC: uma leitura às 23h30 UTC de 05/10 é
     * 20h30 de 05/10 em São Paulo, e agrupar por UTC jogaria registros para o dia errado no
     * relatório de operação.
     *
     * <p>Ordena do mais recente para o mais antigo — quem consulta costuma procurar o que
     * aconteceu há pouco.
     */
    public synchronized List<ResumoDia> agruparPorDia(FiltroHistorico filtro, ZoneId fuso) {
        Map<String, List<SnapshotOperacional>> porDiaEOperador = new LinkedHashMap<>();
        for (SnapshotOperacional snapshot : consultar()) {
            if (!filtro.aceita(snapshot)) {
                continue;
            }
            LocalDate dia = snapshot.instante().atZone(fuso).toLocalDate();
            porDiaEOperador
                .computeIfAbsent(dia + "\u0000" + snapshot.operador(), chave -> new ArrayList<>())
                .add(snapshot);
        }

        List<ResumoDia> resumos = new ArrayList<>();
        for (List<SnapshotOperacional> grupo : porDiaEOperador.values()) {
            resumos.add(resumir(grupo, fuso));
        }
        resumos.sort(
            Comparator.comparing(ResumoDia::dia).thenComparing(ResumoDia::primeiroRegistro).reversed());
        return List.copyOf(resumos);
    }

    private static ResumoDia resumir(List<SnapshotOperacional> grupo, ZoneId fuso) {
        SnapshotOperacional primeiro = grupo.get(0);
        SnapshotOperacional ultimo = grupo.get(grupo.size() - 1);
        int comAlarme = 0;
        int emObservacao = 0;
        int comFalha = 0;
        Set<String> envolvidos = new LinkedHashSet<>();
        String pior = "ESTAVEL";
        for (SnapshotOperacional snapshot : grupo) {
            if (!snapshot.sensoresEmAlarme().isEmpty()) {
                comAlarme++;
                envolvidos.addAll(snapshot.sensoresEmAlarme());
            }
            if (!snapshot.sensoresEmObservacao().isEmpty()) {
                emObservacao++;
            }
            if (snapshot.temFalhaDeSensor()) {
                comFalha++;
                envolvidos.addAll(snapshot.sensoresEmFalha());
            }
            pior = piorEntre(pior, snapshot.statusDerivado());
        }
        return new ResumoDia(
            primeiro.instante().atZone(fuso).toLocalDate(),
            primeiro.operador(),
            primeiro.origemOperador(),
            primeiro.instante(),
            ultimo.instante(),
            grupo.size(),
            comAlarme,
            emObservacao,
            comFalha,
            List.copyOf(envolvidos),
            pior
        );
    }

    private static String piorEntre(String atual, String candidato) {
        return severidade(candidato) > severidade(atual) ? candidato : atual;
    }

    private static int severidade(String status) {
        return switch (status) {
            case "CRITICO" -> 2;
            case "ATENCAO" -> 1;
            default -> 0;
        };
    }

    /**
     * RF17 — conjunto completo que casa com o filtro, <b>sem limite</b>.
     *
     * <p>A consulta da tela limita para não travar o navegador; a exportação não pode limitar,
     * porque um arquivo cortado em silêncio seria pior que nenhum arquivo.
     */
    public synchronized List<SnapshotOperacional> exportar(FiltroHistorico filtro) {
        return consultar().stream().filter(filtro::aceita).toList();
    }

    /** Onde o histórico está gravado, para telas e mensagens. */
    public String descricaoDestino() {
        return TABELA + " em " + banco.descricao();
    }

    /**
     * Traz o CSV legado para a tabela, na mesma ordem (a ordem de inserção vira a ordem de
     * {@code sequencia}). Só roda com a tabela vazia, então é seguro chamar a cada inicialização.
     *
     * @return quantas linhas foram importadas
     */
    public synchronized int importarCsvLegado(Path arquivo) {
        if (!Files.isRegularFile(arquivo) || !consultar().isEmpty()) {
            return 0;
        }
        List<SnapshotOperacional> snapshots = new ArrayList<>();
        try {
            for (String linha : Files.readAllLines(arquivo, StandardCharsets.UTF_8)) {
                SnapshotOperacional snapshot = SnapshotOperacional.deLinhaCsv(linha);
                if (snapshot != null) {
                    snapshots.add(snapshot);
                }
            }
        } catch (IOException error) {
            System.err.println("[HISTORICO] Não foi possível ler " + arquivo + ": " + error.getMessage());
            return 0;
        }
        if (snapshots.isEmpty()) {
            return 0;
        }

        Connection c;
        try {
            c = conexao();
            c.setAutoCommit(false);
        } catch (SQLException error) {
            descartarConexao();
            throw new IllegalStateException("Não foi possível importar o CSV antigo: " + error.getMessage(), error);
        }
        try (PreparedStatement insert = c.prepareStatement(
            "INSERT INTO " + TABELA + " (" + COLUNAS + ") VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)")) {
            try (Statement sql = c.createStatement();
                 ResultSet total = sql.executeQuery("SELECT COUNT(*) FROM " + TABELA)) {
                total.next();
                if (total.getLong(1) > 0) {
                    c.rollback(); // outro processo gravou primeiro; a tabela não está mais vazia
                    return 0;
                }
            }
            for (SnapshotOperacional snapshot : snapshots) {
                preencher(insert, snapshot);
                insert.addBatch();
            }
            insert.executeBatch();
            c.commit();
            return snapshots.size();
        } catch (SQLException error) {
            desfazer(c);
            throw new IllegalStateException("Não foi possível importar o CSV antigo: " + error.getMessage(), error);
        } finally {
            restaurarAutoCommit(c);
        }
    }

    @Override
    public synchronized void close() {
        descartarConexao();
    }

    private Connection conexao() throws SQLException {
        if (conexao == null || conexao.isClosed()) {
            conexao = banco.abrir();
        }
        return conexao;
    }

    /** Fecha uma conexão que deu erro; a próxima operação abre outra (ex.: banco reiniciado). */
    private void descartarConexao() {
        if (conexao == null) {
            return;
        }
        try {
            conexao.close();
        } catch (SQLException ignored) {
            // melhor esforço: a conexão já estava com problema.
        }
        conexao = null;
    }

    private static void desfazer(Connection c) {
        try {
            c.rollback();
        } catch (SQLException ignored) {
            // a transação morre junto com a conexão de qualquer forma.
        }
    }

    private static void restaurarAutoCommit(Connection c) {
        try {
            if (!c.isClosed()) {
                c.setAutoCommit(true);
            }
        } catch (SQLException ignored) {
            // conexão já inutilizada; será reaberta na próxima operação.
        }
    }
}
