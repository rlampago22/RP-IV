-- RNF08 / UC02: "funcionário previamente cadastrado". O Administrador do Sistema emite um código
-- de uso único; só com ele (e a senha) o funcionário consegue cadastrar a biometria do celular.
CREATE TABLE codigo_ativacao (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario BIGINT NOT NULL,
  codigo_hash VARCHAR(100) NOT NULL,
  -- NULL = emitido na instalação do sistema (ativação do primeiro Administrador).
  id_emitido_por BIGINT,
  situacao VARCHAR(20) NOT NULL,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expira_em TIMESTAMP NOT NULL,
  usado_em TIMESTAMP,
  CONSTRAINT fk_codigo_ativacao_usuario FOREIGN KEY (id_usuario) REFERENCES usuario(id),
  CONSTRAINT fk_codigo_ativacao_emissor FOREIGN KEY (id_emitido_por) REFERENCES usuario(id)
);

CREATE INDEX idx_codigo_ativacao_usuario ON codigo_ativacao (id_usuario, situacao);
