-- RF16/RF17 — histórico operacional dos 5 reatores, uma linha por ciclo completo dos 4 sensores
-- RF-1 daquele reator (mesmo modelo de dados que já existia em mvp/dados/historico-operacional.csv,
-- só muda o meio de persistência). As 4 colunas de sensores guardam "id:TIPO" separados por "|",
-- mesma convenção de SnapshotOperacional.linhaCsv()/separar() no mvp/, pra manter compatibilidade.
CREATE TABLE historico_operacional (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reator_id VARCHAR(10) NOT NULL,
  instante TIMESTAMP NOT NULL,
  temperatura DOUBLE PRECISION NOT NULL,
  pressao DOUBLE PRECISION NOT NULL,
  radiacao DOUBLE PRECISION NOT NULL,
  fluxo_resfriamento DOUBLE PRECISION NOT NULL,
  sensores_em_alarme VARCHAR(200) NOT NULL DEFAULT '',
  sensores_reconhecidos VARCHAR(200) NOT NULL DEFAULT '',
  sensores_em_observacao VARCHAR(200) NOT NULL DEFAULT '',
  sensores_em_falha VARCHAR(200) NOT NULL DEFAULT '',
  operador VARCHAR(160) NOT NULL DEFAULT '',
  papeis_operador VARCHAR(200) NOT NULL DEFAULT '',
  origem_operador VARCHAR(30) NOT NULL
);

CREATE INDEX idx_historico_operacional_reator_instante
  ON historico_operacional (reator_id, instante DESC);
