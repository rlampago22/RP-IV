-- RF09 (criar emergência) e RF10 (ativar protocolo de contingência). A ativação e o encerramento são
-- ações críticas: exigem a digital (4.2.10 do PDF, dois fatores para evitar ativação acidental).
CREATE TABLE emergencia (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo VARCHAR(40) NOT NULL,
  descricao VARCHAR(400) NOT NULL,
  status VARCHAR(20) NOT NULL,
  criada_por VARCHAR(160) NOT NULL,
  criada_em TIMESTAMP NOT NULL,
  protocolo VARCHAR(40),
  protocolo_ativado_por VARCHAR(160),
  protocolo_ativado_em TIMESTAMP,
  encerrada_por VARCHAR(160),
  encerrada_em TIMESTAMP
);
