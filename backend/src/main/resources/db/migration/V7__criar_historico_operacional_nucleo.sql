-- Issue #97 (Marco 2, 16/11): histórico operacional (RF16/RF17) sai do arquivo
-- mvp/dados/historico-operacional.csv e passa a morar no banco, no mesmo schema "nucleo" da
-- auditoria (V6) — mesma razão: o núcleo também cria esta tabela sozinho (CREATE ... IF NOT
-- EXISTS, igual a este arquivo) quando sobe antes do backend, e um schema próprio evita que isso
-- deixe o banco de parecer "vazio" para o Flyway.
--
-- Uma linha por mudança de condição (ciclo completo ou alarme/falha) de um reator, mesmo modelo
-- de dados que já existia no CSV (SnapshotOperacional). As 4 colunas de sensores guardam "id:TIPO"
-- separados por "|", mesma convenção de SnapshotOperacional.linhaCsv()/separar(), para manter
-- compatibilidade com o front e com os dados já exportados.
--
-- instante é texto ISO-8601 (Instant.toString), não TIMESTAMP: evita qualquer arredondamento de
-- precisão na volta (mesma razão de nucleo.auditoria_evento.ocorrido_em).
CREATE SCHEMA IF NOT EXISTS nucleo;

CREATE TABLE IF NOT EXISTS nucleo.historico_operacional (
  sequencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reator_id VARCHAR(10) NOT NULL,
  instante VARCHAR(40) NOT NULL,
  temperatura DOUBLE PRECISION NOT NULL,
  pressao DOUBLE PRECISION NOT NULL,
  radiacao DOUBLE PRECISION NOT NULL,
  fluxo_resfriamento DOUBLE PRECISION NOT NULL,
  sensores_em_alarme VARCHAR(200) NOT NULL DEFAULT '',
  sensores_reconhecidos VARCHAR(200) NOT NULL DEFAULT '',
  sensores_em_observacao VARCHAR(200) NOT NULL DEFAULT '',
  sensores_em_falha VARCHAR(200) NOT NULL DEFAULT '',
  operador VARCHAR(160) NOT NULL DEFAULT '',
  papeis_operador VARCHAR(200) NOT NULL DEFAULT '',
  origem_operador VARCHAR(30) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_historico_operacional_reator_instante
  ON nucleo.historico_operacional (reator_id, instante DESC);
